//! v0.5 KAT — codegen cases via `import` + `codegen`.
//!
//! Each case feeds `.proto` editions 2023+ source through
//! `import` (lex + parse + semantic) and then runs
//! `codegen` on the resolved schema; asserts on the emitted
//! Rust source string.
//!
//! Style: snapshot-style. Each expected string is written
//! against the current emitter output rather than against an
//! external reference (`prost`, `protoc`); the v0.5 contract
//! is that the EXACT output shape is locked here so later
//! checkpoints can refactor the emitter freely as long as
//! these snapshots still match.

use grpcx_pb::{codegen, import};

fn render(src: &str) -> String {
    let schema = import(src).unwrap_or_else(|e| panic!("import failed: {e:?}"));
    codegen(&schema)
}

// ============================================================
// 1. Empty schema → header only.
// ============================================================

#[test]
fn empty_schema_emits_header_only() {
    let out = render("edition = \"2023\";\n");
    assert_eq!(out, "// generated by grpcx-pb\n");
}

// ============================================================
// 2. Empty message → struct skeleton.
// ============================================================

#[test]
fn empty_message() {
    let out = render("edition = \"2023\";\nmessage Empty {}\n");
    // Generated headers + struct definition + ProtoCodec impl.
    assert!(out.starts_with("// generated by grpcx-pb\n"));
    assert!(out.contains("#[derive(Debug, Default, Clone, PartialEq)]"));
    assert!(out.contains("pub struct Empty {}"));
    assert!(out.contains("impl ::grpcx_pb::ProtoCodec for Empty {"));
}

