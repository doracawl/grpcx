// ============================================================
// 14. Realistic end-to-end snapshot.
// ============================================================

#[test]
fn realistic_schema_full_snapshot() {
    let out = render(
        r#"
edition = "2023";
package svc;
enum Status { OK = 0; ERR = 1; }
message Request {
  string id = 1;
  repeated string tags = 2;
}
message Response {
  Status status = 1;
  string body = 2;
}
"#,
    );
    // v0.7 reshaped the emission to add `Default` to derives,
    // mark first enum variant `#[default]`, and append a full
    // `ProtoCodec` impl + enum proto_value/from_proto_value
    // helpers. Lock the key surface here via substrings; the
    // earlier full-snapshot lock is dropped because the new
    // emission is roughly 4x longer.
    assert!(out.starts_with("// generated by grpcx-pb\n"));
    assert!(out.contains("pub mod svc {"));
    assert!(out.contains("#[derive(Debug, Default, Clone, PartialEq)]"));
    assert!(out.contains("pub struct Request {"));
    assert!(out.contains("pub id: String,"));
    assert!(out.contains("pub tags: Vec<String>,"));
    assert!(out.contains("impl ::grpcx_pb::ProtoCodec for Request {"));
    // Request encode emits LD tag (1) + as_bytes()
    // length-delimited path for `id`, then a `for __elem`
    // loop over `tags`.
    assert!(out.contains("::grpcx_pb::encode_tag(1, ::grpcx_pb::WireType::LengthDelimited, out);"));
    assert!(out.contains("::grpcx_pb::encode_length_delimited(self.id.as_bytes(), out);"));
    assert!(out.contains("for __elem in &self.tags {"));
    // Response references the enum Status — decode arm uses
    // Status::from_proto_value.
    assert!(out.contains("pub struct Response {"));
    assert!(out.contains("pub status: Status,"));
    assert!(out.contains("impl ::grpcx_pb::ProtoCodec for Response {"));
    assert!(out.contains("self.status.proto_value() as i64 as u64"));
    assert!(out.contains("Status::from_proto_value(__raw as i64 as i32)"));
    // Enum carries Default + proto helpers.
    assert!(out.contains("pub enum Status {"));
    assert!(out.contains("#[default]"));
    assert!(out.contains("OK,"));
    assert!(out.contains("ERR,"));
    assert!(out.contains("impl Status {"));
    assert!(out.contains("pub fn proto_value(&self) -> i32 {"));
    assert!(out.contains("pub fn from_proto_value(v: i32) -> Option<Self> {"));
    assert!(out.contains("Self::OK => 0,"));
    assert!(out.contains("0 => Some(Self::OK),"));
}

// ============================================================
// Service stubs (v1.2 — D2 of the DX pass).
// ============================================================

#[test]
fn service_stub_codegen_shape() {
    let schema = grpcx_pb::import(
        r#"edition = "2023";
package greeter.v1;
message Req { string q = 1; }
message Resp { string a = 1; }
service Greeter {
  rpc SayHello (Req) returns (Resp);
  rpc Watch (Req) returns (stream Resp);
  rpc Upload (stream Req) returns (Resp);
  rpc Chat (stream Req) returns (stream Resp);
}
"#,
    )
    .unwrap();
    let out = grpcx_pb::codegen(&schema);

    // Client: tonic naming habit, snake_case fns, typed IO.
    assert!(out.contains("pub struct GreeterClient;"));
    assert!(out.contains("pub fn say_hello<C: ::grpcx::RpcChannel>(conn: &mut C"));
    assert!(out.contains("ctx: &mut ::grpcx::CallContext, request: &Req)"));
    assert!(out.contains("ctx.set_trailing(__trailing);"));
    assert!(out.contains("request: &Req) -> Result<Resp, ::grpcx::RpcError>"));
    assert!(out.contains("::grpcx::RpcKind::Unary"));
    assert!(out.contains("conn.call_server_streaming(&__method"));
    assert!(out.contains("conn.call_client_streaming(&__method"));
    assert!(out.contains("conn.call_bidi(&__method"));
    // Full wire path carries the package.
    assert!(out.contains("\"greeter.v1.Greeter\""));

    // Handler trait: P2 repaired shape (no Request<T>
    // wrappers — message + CallContext).
    assert!(out.contains("pub trait GreeterHandler {"));
    assert!(out.contains(
        "fn say_hello(&self, request: Req, ctx: &mut ::grpcx::CallContext) -> Result<Resp, ::grpcx::Status>;"
    ));
    assert!(out.contains(
        "fn upload(&self, requests: ::grpcx_pb::alloc::vec::Vec<Req>, ctx: &mut ::grpcx::CallContext) -> Result<Resp, ::grpcx::Status>;"
    ));

    // Server bridge: Service impl + per-method dispatch.
    assert!(out.contains("pub struct GreeterServer<T: GreeterHandler>(pub T);"));
    assert!(out.contains("impl<T: GreeterHandler> ::grpcx::Service for GreeterServer<T>"));
    assert!(out.contains("\"SayHello\" => {"));
    assert!(out.contains("\"Chat\" => {"));
    assert!(out.contains("StatusCode::Unimplemented"));
    assert!(out.contains("__ctx.into_trailing()"));
}

