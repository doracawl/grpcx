//! TypeScript codegen — emits a self-contained `.ts`
//! source from a resolved [`Schema`]. Companion to
//! `codegen.rs` (Rust emitter); the IR (`Schema` /
//! `Message` / `Field` / etc.) is shared.
//!
//! Design (per `_dev/RFC-internal-rpc-arch.md` § 6):
//! - All performance-critical work runs in `@grpcx/native`
//!   (a N-API module that ships in T2.2). The emitted TS
//!   is a thin shim: typed `interface`s for messages, a
//!   `class XxxClient` whose methods call native
//!   `encodeMessage` / `decodeMessage` + the underlying
//!   transport, and a `XxxHandler` interface plus a
//!   `register*` server-side helper.
//! - Field descriptors are emitted as `const`
//!   table objects; the native module consults them when
//!   encoding / decoding plain JS objects.
//! - 64-bit integers map to `bigint` (matching Node's
//!   `BigInt` round-trip with the wire). 32-bit and FP
//!   types map to `number`.
//! - Streaming methods return / take
//!   `AsyncIterable<T>`.

use crate::{Enum, FieldType, Label, Message, Schema};
use alloc::format;
use alloc::string::{String, ToString};
use alloc::vec::Vec;

/// Emit TypeScript source for a resolved [`Schema`].
///
/// The returned string is one self-contained `.ts`
/// file: imports from `@grpcx/core` and `@grpcx/native`,
/// then the message `interface`s, enums, descriptors,
/// and service stubs. The caller writes it to disk
/// (e.g. from a `build.rs`) or pipes it through the
/// downstream TypeScript build.
pub fn codegen_ts(schema: &Schema) -> String {
    let mut em = TsEmitter {
        out: String::new(),
        indent: 0,
    };

    em.line("// Generated by grpcx-pb (TypeScript backend). DO NOT EDIT.");
    em.line(&format!(
        "// Source: package {}, edition {:?}",
        schema.package.as_deref().unwrap_or("<unset>"),
        schema.edition
    ));
    em.line("/* eslint-disable */");
    em.blank();
    em.line("import { Connection, CallContext, Server, Status, StatusCode } from '@grpcx/core';");
    em.line("import { encodeMessage, decodeMessage, FieldDescriptor } from '@grpcx/native';");
    em.blank();

    // Messages first (interfaces + descriptor tables) so
    // services can reference them.
    for msg in &schema.messages {
        emit_message(&mut em, msg);
        em.blank();
    }
    for en in &schema.enums {
        emit_enum(&mut em, en);
        em.blank();
    }
    for svc in &schema.services {
        emit_service(&mut em, svc, schema.package.as_deref());
        em.blank();
    }

    em.out
}

// ============================================================
// Emitter
// ============================================================

struct TsEmitter {
    out: String,
    indent: usize,
}

impl TsEmitter {
    fn line(&mut self, s: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(s);
        self.out.push('\n');
    }
    fn blank(&mut self) {
        self.out.push('\n');
    }
    fn open_block(&mut self, header: &str) {
        self.line(header);
        self.indent += 1;
    }
    fn close_block(&mut self, footer: &str) {
        if self.indent > 0 {
            self.indent -= 1;
        }
        self.line(footer);
    }
}

// ============================================================
// Messages → `interface` + descriptor table
// ============================================================

fn emit_message(em: &mut TsEmitter, msg: &Message) {
    em.open_block(&format!("export interface {} {{", msg.name));
    for f in &msg.fields {
        let ts_ty = field_ts_type(&f.ty, f.label);
        // Always emit `?:` — fields are optional on the
        // JS side regardless of proto3 implicit-presence
        // semantics. The native encoder applies wire-
        // format defaults; consumers omit zero values.
        em.line(&format!("    {}?: {};", camel_case(&f.name), ts_ty));
    }
    em.close_block("}");
    em.blank();
    em.open_block(&format!(
        "export const {}Descriptor: FieldDescriptor[] = [",
        msg.name
    ));
    for f in &msg.fields {
        em.line(&format!(
            "    {{ tag: {}, name: '{}', type: '{}', label: '{}' }},",
            f.number,
            camel_case(&f.name),
            field_descriptor_type(&f.ty),
            label_descriptor(f.label),
        ));
    }
    em.close_block("];");

    // Nested types — emit at module top with parent-
    // prefixed names (TS has no nested classes / inner
    // namespaces for `export interface`; we flatten).
    for nm in &msg.nested_messages {
        em.blank();
        emit_message_with_prefix(em, nm, &msg.name);
    }
    for ne in &msg.nested_enums {
        em.blank();
        emit_enum_with_prefix(em, ne, &msg.name);
    }
}

fn emit_message_with_prefix(em: &mut TsEmitter, msg: &Message, prefix: &str) {
    let qualified_name = format!("{prefix}_{}", msg.name);
    em.open_block(&format!("export interface {qualified_name} {{"));
    for f in &msg.fields {
        let ts_ty = field_ts_type(&f.ty, f.label);
        em.line(&format!("    {}?: {};", camel_case(&f.name), ts_ty));
    }
    em.close_block("}");
    em.blank();
    em.open_block(&format!(
        "export const {qualified_name}Descriptor: FieldDescriptor[] = ["
    ));
    for f in &msg.fields {
        em.line(&format!(
            "    {{ tag: {}, name: '{}', type: '{}', label: '{}' }},",
            f.number,
            camel_case(&f.name),
            field_descriptor_type(&f.ty),
            label_descriptor(f.label),
        ));
    }
    em.close_block("];");
}

fn emit_enum(em: &mut TsEmitter, en: &Enum) {
    em.open_block(&format!("export enum {} {{", en.name));
    for v in &en.values {
        em.line(&format!("    {} = {},", v.name, v.number));
    }
    em.close_block("}");
}

fn emit_enum_with_prefix(em: &mut TsEmitter, en: &Enum, prefix: &str) {
    em.open_block(&format!("export enum {prefix}_{} {{", en.name));
    for v in &en.values {
        em.line(&format!("    {} = {},", v.name, v.number));
    }
    em.close_block("}");
}

// ============================================================
// Services → `class Client` + `interface Handler` +
//             `register*` server-side glue
// ============================================================

fn emit_service(em: &mut TsEmitter, svc: &crate::ServiceDef, package: Option<&str>) {
    let full_name = match package {
        Some(p) => format!("{p}.{}", svc.name),
        None => svc.name.clone(),
    };

    em.line("/// Fully-qualified service name. Mirrors `:service` pseudo-header.");
    em.line(&format!(
        "export const {}_SERVICE_NAME = '{}';",
        const_case(&svc.name),
        full_name
    ));
    em.blank();

    // ---- Client ----
    em.open_block(&format!("export class {}Client {{", svc.name));
    em.line("constructor(private readonly conn: Connection) {}");
    for m in &svc.methods {
        em.blank();
        emit_client_method(em, &full_name, m);
    }
    em.close_block("}");
    em.blank();

    // ---- Handler interface ----
    em.line("/// Server-side handler interface. Implementors");
    em.line("/// pass this to `register");
    em.line(&format!("/// {}(server, impl)`.", svc.name));
    em.open_block(&format!("export interface {}Handler {{", svc.name));
    for m in &svc.methods {
        emit_handler_method(em, m);
    }
    em.close_block("}");
    em.blank();

    // ---- register fn ----
    em.line("/// Register a handler implementation with a `Server`.");
    em.line("/// Mirrors the Rust `Server::register(Box::new(XxxServer(impl)))`");
    em.line("/// pattern.");
    em.open_block(&format!(
        "export function register{}(server: Server, impl_: {}Handler): void {{",
        svc.name, svc.name
    ));
    em.line(&format!(
        "server.registerService({}_SERVICE_NAME, async (method, ctx, requestBodies) => {{",
        const_case(&svc.name)
    ));
    em.indent += 1;
    em.open_block("switch (method) {");
    for m in &svc.methods {
        emit_dispatch_arm(em, m);
    }
    em.line("default: throw new Status(StatusCode.Unimplemented, `unknown method: ${method}`);");
    em.close_block("}");
    em.indent -= 1;
    em.line("});");
    em.close_block("}");
}

fn emit_client_method(em: &mut TsEmitter, full_name: &str, m: &crate::MethodDef) {
    let method_name = camel_case(&m.name);
    let input_t = ts_type_path(&m.input);
    let input_desc = ts_descriptor_path(&m.input);
    let output_t = ts_type_path(&m.output);
    let output_desc = ts_descriptor_path(&m.output);

    let (param, ret) = match (m.client_streaming, m.server_streaming) {
        (false, false) => (
            format!("request: {input_t}"),
            format!("Promise<{output_t}>"),
        ),
        (false, true) => (
            format!("request: {input_t}"),
            format!("AsyncIterable<{output_t}>"),
        ),
        (true, false) => (
            format!("requests: AsyncIterable<{input_t}>"),
            format!("Promise<{output_t}>"),
        ),
        (true, true) => (
            format!("requests: AsyncIterable<{input_t}>"),
            format!("AsyncIterable<{output_t}>"),
        ),
    };

    let prefix = if m.server_streaming {
        "async *"
    } else {
        "async "
    };

    em.line(&format!("/// `{}` rpc.", m.name));
    em.open_block(&format!(
        "{prefix}{method_name}({param}, ctx: CallContext = new CallContext()): {ret} {{"
    ));
    em.line(&format!("const __method = '{}';", m.name));
    em.line(&format!("const __service = '{full_name}';"));
    match (m.client_streaming, m.server_streaming) {
        (false, false) => {
            em.line(&format!(
                "const __body = encodeMessage({input_desc}, request);"
            ));
            em.line("const [__respBody, __trailing] = await this.conn.callUnary(__service, __method, ctx, __body);");
            em.line("ctx.setTrailing(__trailing);");
            em.line(&format!(
                "return decodeMessage({output_desc}, __respBody) as {output_t};"
            ));
        }
        (false, true) => {
            em.line(&format!(
                "const __body = encodeMessage({input_desc}, request);"
            ));
            em.line(
                "const __stream = this.conn.callServerStreaming(__service, __method, ctx, __body);",
            );
            em.line("for await (const __chunk of __stream) {");
            em.line(&format!(
                "    yield decodeMessage({output_desc}, __chunk) as {output_t};"
            ));
            em.line("}");
        }
        (true, false) => {
            em.line("const __requestStream = (async function* () {");
            em.line("    for await (const r of requests) {");
            em.line(&format!("        yield encodeMessage({input_desc}, r);"));
            em.line("    }");
            em.line("})();");
            em.line("const [__respBody, __trailing] = await this.conn.callClientStreaming(__service, __method, ctx, __requestStream);");
            em.line("ctx.setTrailing(__trailing);");
            em.line(&format!(
                "return decodeMessage({output_desc}, __respBody) as {output_t};"
            ));
        }
        (true, true) => {
            em.line("const __requestStream = (async function* () {");
            em.line("    for await (const r of requests) {");
            em.line(&format!("        yield encodeMessage({input_desc}, r);"));
            em.line("    }");
            em.line("})();");
            em.line("const __responseStream = this.conn.callBidi(__service, __method, ctx, __requestStream);");
            em.line("for await (const __chunk of __responseStream) {");
            em.line(&format!(
                "    yield decodeMessage({output_desc}, __chunk) as {output_t};"
            ));
            em.line("}");
        }
    }
    em.close_block("}");
}

fn emit_handler_method(em: &mut TsEmitter, m: &crate::MethodDef) {
    let method_name = camel_case(&m.name);
    let input_t = ts_type_path(&m.input);
    let output_t = ts_type_path(&m.output);
    let (param, ret) = match (m.client_streaming, m.server_streaming) {
        (false, false) => (
            format!("request: {input_t}"),
            format!("Promise<{output_t}>"),
        ),
        (false, true) => (
            format!("request: {input_t}"),
            format!("AsyncIterable<{output_t}>"),
        ),
        (true, false) => (
            format!("requests: AsyncIterable<{input_t}>"),
            format!("Promise<{output_t}>"),
        ),
        (true, true) => (
            format!("requests: AsyncIterable<{input_t}>"),
            format!("AsyncIterable<{output_t}>"),
        ),
    };
    em.line(&format!(
        "/// `{}` rpc handler.\n    {method_name}({param}, ctx: CallContext): {ret};",
        m.name
    ));
}

fn emit_dispatch_arm(em: &mut TsEmitter, m: &crate::MethodDef) {
    let method_name = camel_case(&m.name);
    let input_desc = ts_descriptor_path(&m.input);
    let output_desc = ts_descriptor_path(&m.output);

    em.line(&format!("case '{}': {{", m.name));
    em.indent += 1;
    match (m.client_streaming, m.server_streaming) {
        (false, false) => {
            em.line(&format!(
                "const req = decodeMessage({input_desc}, requestBodies[0]);"
            ));
            em.line(&format!(
                "const resp = await impl_.{method_name}(req as any, ctx);"
            ));
            em.line(&format!("return [encodeMessage({output_desc}, resp)];"));
        }
        (false, true) => {
            em.line(&format!(
                "const req = decodeMessage({input_desc}, requestBodies[0]);"
            ));
            em.line(&format!(
                "const stream = impl_.{method_name}(req as any, ctx);"
            ));
            em.line("const out: Uint8Array[] = [];");
            em.line("for await (const msg of stream) {");
            em.line(&format!("    out.push(encodeMessage({output_desc}, msg));"));
            em.line("}");
            em.line("return out;");
        }
        (true, false) => {
            em.line("const reqStream = (async function* () {");
            em.line("    for (const b of requestBodies) {");
            em.line(&format!("        yield decodeMessage({input_desc}, b);"));
            em.line("    }");
            em.line("})();");
            em.line(&format!(
                "const resp = await impl_.{method_name}(reqStream as any, ctx);"
            ));
            em.line(&format!("return [encodeMessage({output_desc}, resp)];"));
        }
        (true, true) => {
            em.line("const reqStream = (async function* () {");
            em.line("    for (const b of requestBodies) {");
            em.line(&format!("        yield decodeMessage({input_desc}, b);"));
            em.line("    }");
            em.line("})();");
            em.line(&format!(
                "const stream = impl_.{method_name}(reqStream as any, ctx);"
            ));
            em.line("const out: Uint8Array[] = [];");
            em.line("for await (const msg of stream) {");
            em.line(&format!("    out.push(encodeMessage({output_desc}, msg));"));
            em.line("}");
            em.line("return out;");
        }
    }
    em.indent -= 1;
    em.line("}");
}

// ============================================================
// Type / descriptor mapping
// ============================================================

fn field_ts_type(ty: &FieldType, label: Label) -> String {
    let base = scalar_ts_type(ty);
    match label {
        Label::Repeated => format!("{base}[]"),
        _ => base,
    }
}

fn scalar_ts_type(ty: &FieldType) -> String {
    match ty {
        FieldType::Int32
        | FieldType::Sint32
        | FieldType::Sfixed32
        | FieldType::Fixed32
        | FieldType::Uint32
        | FieldType::Float
        | FieldType::Double => "number".to_string(),
        FieldType::Int64
        | FieldType::Sint64
        | FieldType::Sfixed64
        | FieldType::Fixed64
        | FieldType::Uint64 => "bigint".to_string(),
        FieldType::Bool => "boolean".to_string(),
        FieldType::String_ => "string".to_string(),
        FieldType::Bytes => "Uint8Array".to_string(),
        FieldType::Message(fqn) | FieldType::Enum(fqn) => ts_type_path(fqn),
        FieldType::Map { key, value } => {
            let k = scalar_ts_type(key);
            let v = scalar_ts_type(value);
            format!("Map<{k}, {v}>")
        }
    }
}

/// Wire-format type tag for the descriptor table.
fn field_descriptor_type(ty: &FieldType) -> &'static str {
    match ty {
        FieldType::Int32 => "int32",
        FieldType::Int64 => "int64",
        FieldType::Uint32 => "uint32",
        FieldType::Uint64 => "uint64",
        FieldType::Sint32 => "sint32",
        FieldType::Sint64 => "sint64",
        FieldType::Fixed32 => "fixed32",
        FieldType::Fixed64 => "fixed64",
        FieldType::Sfixed32 => "sfixed32",
        FieldType::Sfixed64 => "sfixed64",
        FieldType::Float => "float",
        FieldType::Double => "double",
        FieldType::Bool => "bool",
        FieldType::String_ => "string",
        FieldType::Bytes => "bytes",
        FieldType::Message(_) => "message",
        FieldType::Enum(_) => "enum",
        FieldType::Map { .. } => "map",
    }
}

fn label_descriptor(label: Label) -> &'static str {
    match label {
        Label::Singular => "singular",
        Label::Optional => "optional",
        Label::Repeated => "repeated",
    }
}

/// Map a fully-qualified proto type name to a TS path.
/// Same-package types are referenced by bare local name
/// (the schema's types live in one TS module). Cross-
/// package refs collapse the package qualifier (TS has
/// no namespace nesting in the emitted module).
fn ts_type_path(proto_ty: &str) -> String {
    proto_ty.rsplit('.').next().unwrap_or(proto_ty).to_string()
}

fn ts_descriptor_path(proto_ty: &str) -> String {
    let base = ts_type_path(proto_ty);
    format!("{base}Descriptor")
}

/// `say_hello` / `SayHello` → `sayHello`.
fn camel_case(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut upper_next = false;
    for (i, c) in name.chars().enumerate() {
        if c == '_' {
            upper_next = true;
            continue;
        }
        if i == 0 {
            out.push(c.to_ascii_lowercase());
        } else if upper_next {
            out.push(c.to_ascii_uppercase());
            upper_next = false;
        } else {
            out.push(c);
        }
    }
    out
}

/// `Greeter` → `GREETER`.
fn const_case(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 4);
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() && i > 0 {
            out.push('_');
        }
        out.push(c.to_ascii_uppercase());
    }
    out
}

