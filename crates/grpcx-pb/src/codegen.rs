//! Codegen: resolved `Schema` → L7 IDL Rust source string.
//!
//! See `../../REFACTOR-v8-v0.5-codegen.md` for the original
//! v0.5 design + tradeoffs and
//! `../../REFACTOR-v8-v0.7-close-out.md` for the v0.7
//! `ProtoCodec` emission extension (closes the v0.5 enum-
//! value-lost limitation + the v0.6 codegen-emit gap).

use crate::{Enum, Field, FieldType, Label, Message, Schema};
use alloc::format;
use alloc::string::{String, ToString};
use alloc::vec::Vec;

/// Emit Rust source for a **resolved** schema (post-v0.4
/// semantic analysis — every named type ref must already be
/// FQN-rewritten and Message/Enum-classified).
///
/// Returns a single `String` containing the generated Rust.
/// The caller decides whether to feed it to `build.rs`, a
/// proc-macro, `syn::parse_file`, etc.
///
/// # Example
///
/// ```rust,ignore
/// let schema = grpcx_pb::import(proto_source)?;
/// let rust = grpcx_pb::codegen(&schema);
/// std::fs::write("out.rs", rust)?;
/// ```
pub fn codegen(schema: &Schema) -> String {
    let pkg_segs: Vec<String> = schema
        .package
        .as_deref()
        .map(|s| s.split('.').map(String::from).collect())
        .unwrap_or_default();
    let mut em = Emitter {
        out: String::new(),
        indent: 0,
        pkg_prefix_len: pkg_segs.len(),
    };
    em.line("// generated by grpcx-pb");
    for s in &pkg_segs {
        em.open_block(&fmt_mod_open(s));
    }
    let scope = pkg_segs.clone();
    for (i, msg) in schema.messages.iter().enumerate() {
        if i > 0 {
            em.blank();
        }
        emit_message(&mut em, msg, &scope);
    }
    if !schema.messages.is_empty() && !schema.enums.is_empty() {
        em.blank();
    }
    for (i, en) in schema.enums.iter().enumerate() {
        if i > 0 {
            em.blank();
        }
        emit_enum(&mut em, en, &scope);
    }
    if !schema.services.is_empty() {
        em.blank();
    }
    for (i, svc) in schema.services.iter().enumerate() {
        if i > 0 {
            em.blank();
        }
        emit_service_stubs(&mut em, svc, schema.package.as_deref());
    }
    for _ in &pkg_segs {
        em.close_block("}");
    }
    em.out
}

// ============================================================
// Emitter.
// ============================================================

struct Emitter {
    out: String,
    indent: u32,
    pkg_prefix_len: usize,
}

impl Emitter {
    fn line(&mut self, s: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(s);
        self.out.push('\n');
    }

    fn open_block(&mut self, header: &str) {
        self.line(header);
        self.indent += 1;
    }

    fn close_block(&mut self, footer: &str) {
        self.indent = self.indent.saturating_sub(1);
        self.line(footer);
    }

    fn blank(&mut self) {
        self.out.push('\n');
    }
}

fn fmt_mod_open(name: &str) -> String {
    let mut s = String::from("pub mod ");
    s.push_str(name);
    s.push_str(" {");
    s
}

// ============================================================
// Message + enum emission.
// ============================================================

fn emit_message(em: &mut Emitter, msg: &Message, current_mod: &[String]) {
    em.line("#[derive(Debug, Default, Clone, PartialEq)]");
    if msg.fields.is_empty() {
        let mut header = String::from("pub struct ");
        header.push_str(&msg.name);
        header.push_str(" {}");
        em.line(&header);
    } else {
        let mut header = String::from("pub struct ");
        header.push_str(&msg.name);
        header.push_str(" {");
        em.open_block(&header);
        for f in &msg.fields {
            let ty = field_type_to_rust(&f.ty, f.label, current_mod, em.pkg_prefix_len);
            let mut line = String::from("pub ");
            line.push_str(&escape_rust_ident(&f.name));
            line.push_str(": ");
            line.push_str(&ty);
            line.push(',');
            em.line(&line);
        }
        em.close_block("}");
    }
    emit_proto_codec_for_message(em, msg, current_mod);
    if !msg.nested_messages.is_empty() || !msg.nested_enums.is_empty() {
        let mod_name = to_snake_case(&msg.name);
        em.open_block(&fmt_mod_open(&mod_name));
        let mut child_scope: Vec<String> = current_mod.to_vec();
        child_scope.push(mod_name);
        for (i, nm) in msg.nested_messages.iter().enumerate() {
            if i > 0 {
                em.blank();
            }
            emit_message(em, nm, &child_scope);
        }
        if !msg.nested_messages.is_empty() && !msg.nested_enums.is_empty() {
            em.blank();
        }
        for (i, ne) in msg.nested_enums.iter().enumerate() {
            if i > 0 {
                em.blank();
            }
            emit_enum(em, ne, &child_scope);
        }
        em.close_block("}");
    }
}

fn emit_enum(em: &mut Emitter, en: &Enum, _current_mod: &[String]) {
    if en.values.is_empty() {
        em.line("#[derive(Debug, Clone, PartialEq)]");
        let mut header = String::from("pub enum ");
        header.push_str(&en.name);
        header.push_str(" {}");
        em.line(&header);
        return;
    }
    em.line("#[derive(Debug, Default, Clone, PartialEq)]");
    let mut header = String::from("pub enum ");
    header.push_str(&en.name);
    header.push_str(" {");
    em.open_block(&header);
    for (i, v) in en.values.iter().enumerate() {
        if i == 0 {
            em.line("#[default]");
        }
        let mut line = escape_rust_ident(&v.name);
        line.push(',');
        em.line(&line);
    }
    em.close_block("}");
    emit_enum_proto_methods(em, en);
}

// ============================================================
// ProtoCodec impl emission for messages.
// ============================================================
//
// Layout per message:
//
//     impl ::grpcx_pb::ProtoCodec for <Msg> {
//         fn encode(&self, out: &mut ::grpcx_pb::alloc::vec::Vec<u8>) { … }
//         fn decode(bytes: &[u8]) -> Result<Self, ::grpcx_pb::WireError> { … }
//     }
//
// For messages containing a `map<K, V>` field anywhere, emit a
// `compile_error!` stub (v0.7 doesn't ship map wire codegen).

fn emit_proto_codec_for_message(em: &mut Emitter, msg: &Message, current_mod: &[String]) {
    let mut header = String::from("impl ::grpcx_pb::ProtoCodec for ");
    header.push_str(&msg.name);
    header.push_str(" {");
    em.open_block(&header);
    if has_map_field(msg) {
        em.line("// v0.7: map<K, V> wire codegen is deferred to v1.x.");
        em.line("// Hand-write `ProtoCodec` for this message until then.");
        em.line(
            "fn encode(&self, _out: &mut ::grpcx_pb::alloc::vec::Vec<u8>) { compile_error!(\"`map<K, V>` ProtoCodec codegen is deferred to grpcx-pb v1.x — hand-write `ProtoCodec` for this message until then\"); }",
        );
        em.line(
            "fn decode(_bytes: &[u8]) -> Result<Self, ::grpcx_pb::WireError> { compile_error!(\"`map<K, V>` ProtoCodec codegen is deferred to grpcx-pb v1.x — hand-write `ProtoCodec` for this message until then\"); }",
        );
        em.close_block("}");
        return;
    }
    // encode
    em.open_block("fn encode(&self, out: &mut ::grpcx_pb::alloc::vec::Vec<u8>) {");
    if msg.fields.is_empty() {
        em.line("let _ = out;");
    } else {
        for f in &msg.fields {
            emit_encode_field(em, f, current_mod);
        }
    }
    em.close_block("}");
    // decode
    em.open_block("fn decode(bytes: &[u8]) -> Result<Self, ::grpcx_pb::WireError> {");
    em.line("let mut __out: Self = ::core::default::Default::default();");
    em.line("let mut __pos: usize = 0;");
    em.open_block("while __pos < bytes.len() {");
    em.line("let (__field, __wire, __n) = ::grpcx_pb::decode_tag(&bytes[__pos..])?;");
    em.line("__pos += __n;");
    em.open_block("match (__field, __wire) {");
    for f in &msg.fields {
        emit_decode_arm(em, f, current_mod);
    }
    em.open_block("(_, __wt) => {");
    em.line("let __n = ::grpcx_pb::skip_field(__wt, &bytes[__pos..])?;");
    em.line("__pos += __n;");
    em.close_block("}");
    em.close_block("}");
    em.close_block("}");
    em.line("Ok(__out)");
    em.close_block("}");
    em.close_block("}");
}

fn emit_encode_field(em: &mut Emitter, f: &Field, _current_mod: &[String]) {
    let wt = wire_type_name(&f.ty);
    let escaped_name = escape_rust_ident(&f.name);
    match f.label {
        Label::Repeated => {
            em.open_block(&format!("for __elem in &self.{escaped_name} {{"));
        }
        // Explicit presence (stage B): Some(default) goes
        // ON the wire; None doesn't.
        Label::Optional => {
            em.open_block(&format!("if let Some(__v) = &self.{escaped_name} {{"));
        }
        Label::Singular => {}
    }
    em.line(&format!(
        "::grpcx_pb::encode_tag({}, ::grpcx_pb::WireType::{}, out);",
        f.number, wt
    ));
    emit_encode_value(em, &f.ty, f.label, &escaped_name);
    if matches!(f.label, Label::Repeated | Label::Optional) {
        em.close_block("}");
    }
}

/// Emit the encode expression for a single field value.
///
/// Per-label accessors:
/// - `val` — a value expression usable for numeric casts and
///   `if`-conditions. Singular: `self.<f>`. Repeated:
///   `(*__elem)` (deref the `&T` element).
/// - `mthd` — a method-call target relying on auto-deref.
///   Singular: `self.<f>`. Repeated: `__elem`.
/// - `refr` — a `&T` reference (needed for
///   `ProtoCodec::encode`). Singular: `&self.<f>`. Repeated:
///   `__elem` (already a reference).
fn emit_encode_value(em: &mut Emitter, ty: &FieldType, label: Label, field_name: &str) {
    let val: String = match label {
        Label::Singular => format!("self.{field_name}"),
        Label::Optional => String::from("(*__v)"),
        Label::Repeated => String::from("(*__elem)"),
    };
    let mthd: String = match label {
        Label::Singular => format!("self.{field_name}"),
        Label::Optional => String::from("__v"),
        Label::Repeated => String::from("__elem"),
    };
    let refr: String = match label {
        Label::Singular => format!("&self.{field_name}"),
        Label::Optional => String::from("__v"),
        Label::Repeated => String::from("__elem"),
    };
    match ty {
        FieldType::Int32 | FieldType::Int64 => {
            em.line(&format!(
                "::grpcx_pb::encode_varint({val} as i64 as u64, out);"
            ));
        }
        FieldType::Uint32 | FieldType::Uint64 => {
            em.line(&format!("::grpcx_pb::encode_varint({val} as u64, out);"));
        }
        FieldType::Sint32 => {
            em.line(&format!(
                "::grpcx_pb::encode_varint(::grpcx_pb::zigzag_encode_i32({val}), out);"
            ));
        }
        FieldType::Sint64 => {
            em.line(&format!(
                "::grpcx_pb::encode_varint(::grpcx_pb::zigzag_encode_i64({val}), out);"
            ));
        }
        FieldType::Fixed32 => {
            em.line(&format!("::grpcx_pb::encode_fixed32({val}, out);"));
        }
        FieldType::Sfixed32 => {
            em.line(&format!("::grpcx_pb::encode_fixed32({val} as u32, out);"));
        }
        FieldType::Float => {
            em.line(&format!(
                "::grpcx_pb::encode_fixed32({mthd}.to_bits(), out);"
            ));
        }
        FieldType::Fixed64 => {
            em.line(&format!("::grpcx_pb::encode_fixed64({val}, out);"));
        }
        FieldType::Sfixed64 => {
            em.line(&format!("::grpcx_pb::encode_fixed64({val} as u64, out);"));
        }
        FieldType::Double => {
            em.line(&format!(
                "::grpcx_pb::encode_fixed64({mthd}.to_bits(), out);"
            ));
        }
        FieldType::Bool => {
            em.line(&format!(
                "::grpcx_pb::encode_varint(if {val} {{ 1 }} else {{ 0 }}, out);"
            ));
        }
        FieldType::String_ => {
            em.line(&format!(
                "::grpcx_pb::encode_length_delimited({mthd}.as_bytes(), out);"
            ));
        }
        FieldType::Bytes => {
            em.line(&format!(
                "::grpcx_pb::encode_length_delimited({mthd}.as_slice(), out);"
            ));
        }
        FieldType::Message(_) => {
            em.line("{");
            em.line("    let mut __sub: ::grpcx_pb::alloc::vec::Vec<u8> = ::grpcx_pb::alloc::vec::Vec::new();");
            em.line(&format!(
                "    ::grpcx_pb::ProtoCodec::encode({refr}, &mut __sub);"
            ));
            em.line("    ::grpcx_pb::encode_length_delimited(&__sub, out);");
            em.line("}");
        }
        FieldType::Enum(_) => {
            em.line(&format!(
                "::grpcx_pb::encode_varint({mthd}.proto_value() as i64 as u64, out);"
            ));
        }
        FieldType::Map { .. } => {
            em.line("// unreachable: map fields short-circuit at emit_proto_codec_for_message");
        }
    }
}

fn emit_decode_arm(em: &mut Emitter, f: &Field, current_mod: &[String]) {
    let wt = wire_type_name(&f.ty);
    let escaped_name = escape_rust_ident(&f.name);
    em.open_block(&format!(
        "({}, ::grpcx_pb::WireType::{}) => {{",
        f.number, wt
    ));
    emit_decode_value(em, &f.ty, &escaped_name, f.label, current_mod);
    em.close_block("}");
}

fn emit_decode_value(
    em: &mut Emitter,
    ty: &FieldType,
    field_name: &str,
    label: Label,
    current_mod: &[String],
) {
    let assign_target = match label {
        Label::Singular => format!("__out.{field_name}"),
        Label::Optional | Label::Repeated => String::from("__v"),
    };
    let pkg_prefix_len = em.pkg_prefix_len;
    if matches!(label, Label::Repeated | Label::Optional) {
        let ty_str = field_type_to_rust(ty, Label::Singular, current_mod, pkg_prefix_len);
        em.line(&format!("let __v: {ty_str};"));
    }
    match ty {
        FieldType::Int32 => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_varint(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = __raw as i64 as i32;"));
            em.line("__pos += __n;");
        }
        FieldType::Int64 => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_varint(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = __raw as i64;"));
            em.line("__pos += __n;");
        }
        FieldType::Uint32 => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_varint(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = __raw as u32;"));
            em.line("__pos += __n;");
        }
        FieldType::Uint64 => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_varint(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = __raw;"));
            em.line("__pos += __n;");
        }
        FieldType::Sint32 => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_varint(&bytes[__pos..])?;");
            em.line(&format!(
                "{assign_target} = ::grpcx_pb::zigzag_decode_i32(__raw);"
            ));
            em.line("__pos += __n;");
        }
        FieldType::Sint64 => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_varint(&bytes[__pos..])?;");
            em.line(&format!(
                "{assign_target} = ::grpcx_pb::zigzag_decode_i64(__raw);"
            ));
            em.line("__pos += __n;");
        }
        FieldType::Fixed32 => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_fixed32(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = __raw;"));
            em.line("__pos += __n;");
        }
        FieldType::Sfixed32 => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_fixed32(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = __raw as i32;"));
            em.line("__pos += __n;");
        }
        FieldType::Float => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_fixed32(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = f32::from_bits(__raw);"));
            em.line("__pos += __n;");
        }
        FieldType::Fixed64 => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_fixed64(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = __raw;"));
            em.line("__pos += __n;");
        }
        FieldType::Sfixed64 => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_fixed64(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = __raw as i64;"));
            em.line("__pos += __n;");
        }
        FieldType::Double => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_fixed64(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = f64::from_bits(__raw);"));
            em.line("__pos += __n;");
        }
        FieldType::Bool => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_varint(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = __raw != 0;"));
            em.line("__pos += __n;");
        }
        FieldType::String_ => {
            em.line("let (__s, __n) = ::grpcx_pb::decode_string(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = __s;"));
            em.line("__pos += __n;");
        }
        FieldType::Bytes => {
            em.line("let (__slice, __n) = ::grpcx_pb::decode_length_delimited(&bytes[__pos..])?;");
            em.line(&format!("{assign_target} = __slice.to_vec();"));
            em.line("__pos += __n;");
        }
        FieldType::Message(_) => {
            em.line("let (__slice, __n) = ::grpcx_pb::decode_length_delimited(&bytes[__pos..])?;");
            em.line(&format!(
                "{assign_target} = ::grpcx_pb::ProtoCodec::decode(__slice)?;"
            ));
            em.line("__pos += __n;");
        }
        FieldType::Enum(fqn) => {
            em.line("let (__raw, __n) = ::grpcx_pb::decode_varint(&bytes[__pos..])?;");
            let path = fqn_to_rust_path(fqn, current_mod, pkg_prefix_len);
            em.line(&format!(
                "{assign_target} = match {path}::from_proto_value(__raw as i64 as i32) {{ Some(__got) => __got, None => return Err(::grpcx_pb::WireError::UnsupportedFeature(\"unknown enum value\")), }};"
            ));
            em.line("__pos += __n;");
        }
        FieldType::Map { .. } => {
            em.line("// unreachable: map fields short-circuit at emit_proto_codec_for_message");
        }
    }
    match label {
        Label::Repeated => {
            em.line(&format!("__out.{field_name}.push(__v);"));
        }
        Label::Optional => {
            em.line(&format!(
                "__out.{field_name} = ::core::option::Option::Some(__v);"
            ));
        }
        Label::Singular => {}
    }
}

fn has_map_field(msg: &Message) -> bool {
    msg.fields.iter().any(|f| field_has_map(&f.ty))
}

fn field_has_map(ty: &FieldType) -> bool {
    match ty {
        FieldType::Map { .. } => true,
        FieldType::Message(_) | FieldType::Enum(_) => false,
        _ => false,
    }
}

fn wire_type_name(ty: &FieldType) -> &'static str {
    match ty {
        FieldType::Int32
        | FieldType::Int64
        | FieldType::Uint32
        | FieldType::Uint64
        | FieldType::Sint32
        | FieldType::Sint64
        | FieldType::Bool
        | FieldType::Enum(_) => "Varint",
        FieldType::Fixed32 | FieldType::Sfixed32 | FieldType::Float => "Fixed32",
        FieldType::Fixed64 | FieldType::Sfixed64 | FieldType::Double => "Fixed64",
        FieldType::String_ | FieldType::Bytes | FieldType::Message(_) | FieldType::Map { .. } => {
            "LengthDelimited"
        }
    }
}

// ============================================================
// Enum proto_value / from_proto_value helper methods.
// ============================================================

fn emit_enum_proto_methods(em: &mut Emitter, en: &Enum) {
    let mut header = String::from("impl ");
    header.push_str(&en.name);
    header.push_str(" {");
    em.open_block(&header);
    // proto_value
    em.open_block("pub fn proto_value(&self) -> i32 {");
    em.open_block("match self {");
    for v in &en.values {
        em.line(&format!(
            "Self::{} => {},",
            escape_rust_ident(&v.name),
            v.number
        ));
    }
    em.close_block("}");
    em.close_block("}");
    // from_proto_value
    em.open_block("pub fn from_proto_value(v: i32) -> Option<Self> {");
    em.open_block("match v {");
    for val in &en.values {
        em.line(&format!(
            "{} => Some(Self::{}),",
            val.number,
            escape_rust_ident(&val.name)
        ));
    }
    em.line("_ => None,");
    em.close_block("}");
    em.close_block("}");
    em.close_block("}");
}

// ============================================================
// Field-type → Rust string.
// ============================================================

fn field_type_to_rust(
    ty: &FieldType,
    label: Label,
    current_mod: &[String],
    pkg_prefix_len: usize,
) -> String {
    let base = match ty {
        FieldType::Int32 | FieldType::Sint32 | FieldType::Sfixed32 => "i32".to_string(),
        FieldType::Int64 | FieldType::Sint64 | FieldType::Sfixed64 => "i64".to_string(),
        FieldType::Uint32 | FieldType::Fixed32 => "u32".to_string(),
        FieldType::Uint64 | FieldType::Fixed64 => "u64".to_string(),
        FieldType::Float => "f32".to_string(),
        FieldType::Double => "f64".to_string(),
        FieldType::Bool => "bool".to_string(),
        FieldType::String_ => "String".to_string(),
        FieldType::Bytes => "Vec<u8>".to_string(),
        FieldType::Message(fqn) | FieldType::Enum(fqn) => {
            fqn_to_rust_path(fqn, current_mod, pkg_prefix_len)
        }
        FieldType::Map { key, value } => {
            let k = field_type_to_rust(key, Label::Singular, current_mod, pkg_prefix_len);
            let v = field_type_to_rust(value, Label::Singular, current_mod, pkg_prefix_len);
            let mut s = String::from("Vec<(");
            s.push_str(&k);
            s.push_str(", ");
            s.push_str(&v);
            s.push_str(")>");
            s
        }
    };
    match label {
        Label::Singular => base,
        Label::Optional => {
            let mut s = String::from("Option<");
            s.push_str(&base);
            s.push('>');
            s
        }
        Label::Repeated => {
            let mut s = String::from("Vec<");
            s.push_str(&base);
            s.push('>');
            s
        }
    }
}

// ============================================================
// FQN → Rust path.
// ============================================================

fn fqn_to_rust_path(fqn: &str, current_mod: &[String], pkg_prefix_len: usize) -> String {
    let segs: Vec<&str> = fqn.split('.').collect();
    let last = segs.len() - 1;
    let mut target_mod: Vec<String> = Vec::with_capacity(last);
    for (i, s) in segs[..last].iter().enumerate() {
        if i < pkg_prefix_len {
            target_mod.push((*s).to_string());
        } else {
            target_mod.push(to_snake_case(s));
        }
    }
    let type_name = (*segs.last().unwrap()).to_string();
    relative_path(current_mod, &target_mod, &type_name)
}

fn relative_path(current: &[String], target: &[String], type_name: &str) -> String {
    let mut common = 0;
    while common < current.len() && common < target.len() && current[common] == target[common] {
        common += 1;
    }
    let supers = current.len() - common;
    let mut parts: Vec<String> = Vec::new();
    for _ in 0..supers {
        parts.push("super".to_string());
    }
    for s in &target[common..] {
        parts.push(s.clone());
    }
    parts.push(type_name.to_string());
    parts.join("::")
}

// ============================================================
// Snake-case + raw-ident escape.
// ============================================================

fn to_snake_case(s: &str) -> String {
    let mut out = String::new();
    let mut prev_upper = false;
    for (i, c) in s.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 && !prev_upper && !out.ends_with('_') {
                out.push('_');
            }
            prev_upper = true;
            out.push(c.to_ascii_lowercase());
        } else {
            prev_upper = false;
            out.push(c);
        }
    }
    out
}

/// Rust reserved keywords (2021 / 2024 editions). Used by
/// [`escape_rust_ident`] to decide whether a protobuf
/// identifier needs the `r#…` raw-ident escape, a trailing
/// underscore, or pass-through.
const RUST_KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false",
    "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
    "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while",
    "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized",
    "virtual", "yield", "try",
];

/// Rust keywords that **cannot** be used as raw identifiers
/// (they retain syntactic meaning even with `r#`). For these
/// we fall back to a trailing underscore.
const RUST_HARD_KEYWORDS: &[&str] = &["crate", "self", "Self", "super"];

fn escape_rust_ident(name: &str) -> String {
    if RUST_HARD_KEYWORDS.contains(&name) {
        let mut s = String::from(name);
        s.push('_');
        return s;
    }
    if RUST_KEYWORDS.contains(&name) {
        let mut s = String::from("r#");
        s.push_str(name);
        return s;
    }
    name.to_string()
}

// ============================================================
// Service stubs (D2 of the DX pass — docs/dx-scope.md).
//
// For each `service` the generated module gains:
//   - `<Name>Client`: per-rpc typed fns over a `Channel` +
//     `DatagramTransport` (blocking facades).
//   - `<Name>Handler` trait: one fn per rpc in the P2
//     repaired shape — message in, `&mut CallContext`,
//     `Result<message, Status>` out. Streaming rpcs use
//     Vec batch shapes matching the L10 transport.
//   - `<Name>Server<T>`: wraps a handler, implements
//     `::grpcx::Service` with the decode/dispatch/encode
//     bridge.
//
// The emitted code references `::grpcx` — consumers depend
// on both `grpcx` and `grpcx-pb`. grpcx-pb itself never
// depends on L10 (layer direction holds; this is string
// emission only).
// ============================================================

fn emit_service_stubs(em: &mut Emitter, svc: &crate::ServiceDef, package: Option<&str>) {
    let full_name = match package {
        Some(p) => alloc::format!("{p}.{}", svc.name),
        None => svc.name.clone(),
    };

    // ---- Client ----
    em.line("/// Generated typed client (blocking facades).");
    em.line(&alloc::format!("pub struct {}Client;", svc.name));
    em.blank();
    em.open_block(&alloc::format!("impl {}Client {{", svc.name));
    for (i, m) in svc.methods.iter().enumerate() {
        if i > 0 {
            em.blank();
        }
        emit_client_method(em, &full_name, m);
    }
    em.close_block("}");
    em.blank();

    // ---- Handler trait ----
    em.line("/// Generated server-side handler trait —");
    em.line("/// implement one fn per rpc.");
    em.open_block(&alloc::format!("pub trait {}Handler {{", svc.name));
    for m in &svc.methods {
        emit_handler_sig(em, m, true);
    }
    em.close_block("}");
    em.blank();

    // ---- Server wrapper ----
    em.line("/// Generated `::grpcx::Service` bridge — register");
    em.line("/// with `Server::register(Box::new(XxxServer(handler)))`.");
    em.line(&alloc::format!(
        "pub struct {}Server<T: {}Handler>(pub T);",
        svc.name,
        svc.name
    ));
    em.blank();
    em.open_block(&alloc::format!(
        "impl<T: {}Handler> ::grpcx::Service for {}Server<T> {{",
        svc.name,
        svc.name
    ));
    em.open_block("fn name(&self) -> &str {");
    em.line(&alloc::format!("\"{full_name}\""));
    em.close_block("}");
    em.blank();
    emit_dispatch_bridge(em, svc);
    em.close_block("}");
}

fn emit_client_method(em: &mut Emitter, full_name: &str, m: &crate::MethodDef) {
    let fn_name = to_snake(&m.name);
    let input = rust_type_path(&m.input);
    let output = rust_type_path(&m.output);
    let kind = match (m.client_streaming, m.server_streaming) {
        (false, false) => "Unary",
        (false, true) => "ServerStreaming",
        (true, false) => "ClientStreaming",
        (true, true) => "BidirectionalStreaming",
    };

    let (params, ret) = match (m.client_streaming, m.server_streaming) {
        (false, false) => (
            alloc::format!("request: &{input}"),
            alloc::format!("Result<{output}, ::grpcx::RpcError>"),
        ),
        (false, true) => (
            alloc::format!("request: &{input}"),
            alloc::format!("Result<::grpcx_pb::alloc::vec::Vec<{output}>, ::grpcx::RpcError>"),
        ),
        (true, false) => (
            alloc::format!("requests: &[{input}]"),
            alloc::format!("Result<{output}, ::grpcx::RpcError>"),
        ),
        (true, true) => (
            alloc::format!("requests: &[{input}]"),
            alloc::format!("Result<::grpcx_pb::alloc::vec::Vec<{output}>, ::grpcx::RpcError>"),
        ),
    };

    em.line(&alloc::format!("/// `{}` rpc.", m.name));
    em.open_block(&alloc::format!(
        "pub fn {fn_name}<C: ::grpcx::RpcChannel>(conn: &mut C, ctx: &mut ::grpcx::CallContext, {params}) -> {ret} {{"
    ));
    em.line(&alloc::format!(
        "let __method = ::grpcx::Method {{ service: ::grpcx_pb::alloc::string::String::from(\"{full_name}\"), method: ::grpcx_pb::alloc::string::String::from(\"{}\"), kind: ::grpcx::RpcKind::{kind} }};",
        m.name
    ));
    match (m.client_streaming, m.server_streaming) {
        (false, false) => {
            em.line("let mut __buf = ::grpcx_pb::alloc::vec::Vec::new();");
            em.line("::grpcx_pb::ProtoCodec::encode(request, &mut __buf);");
            em.line("let (__resp, __trailing) = conn.call_unary(&__method, &ctx.request_metadata().clone(), &__buf)?;");
            em.line("ctx.set_trailing(__trailing);");
            em.line("::grpcx_pb::ProtoCodec::decode(&__resp).map_err(|_| ::grpcx::RpcError::Codec(\"response decode\"))");
        }
        (false, true) => {
            em.line("let mut __buf = ::grpcx_pb::alloc::vec::Vec::new();");
            em.line("::grpcx_pb::ProtoCodec::encode(request, &mut __buf);");
            em.line("let (__msgs, __trailing) = conn.call_server_streaming(&__method, &ctx.request_metadata().clone(), &__buf)?;");
            em.line("ctx.set_trailing(__trailing);");
            em.line("__msgs.iter().map(|m| ::grpcx_pb::ProtoCodec::decode(m).map_err(|_| ::grpcx::RpcError::Codec(\"response decode\"))).collect()");
        }
        (true, false) => {
            em.line("let __bufs: ::grpcx_pb::alloc::vec::Vec<::grpcx_pb::alloc::vec::Vec<u8>> = requests.iter().map(|r| { let mut b = ::grpcx_pb::alloc::vec::Vec::new(); ::grpcx_pb::ProtoCodec::encode(r, &mut b); b }).collect();");
            em.line("let __refs: ::grpcx_pb::alloc::vec::Vec<&[u8]> = __bufs.iter().map(|b| b.as_slice()).collect();");
            em.line("let (__resp, __trailing) = conn.call_client_streaming(&__method, &ctx.request_metadata().clone(), &__refs)?;");
            em.line("ctx.set_trailing(__trailing);");
            em.line("::grpcx_pb::ProtoCodec::decode(&__resp).map_err(|_| ::grpcx::RpcError::Codec(\"response decode\"))");
        }
        (true, true) => {
            em.line("let __bufs: ::grpcx_pb::alloc::vec::Vec<::grpcx_pb::alloc::vec::Vec<u8>> = requests.iter().map(|r| { let mut b = ::grpcx_pb::alloc::vec::Vec::new(); ::grpcx_pb::ProtoCodec::encode(r, &mut b); b }).collect();");
            em.line("let __refs: ::grpcx_pb::alloc::vec::Vec<&[u8]> = __bufs.iter().map(|b| b.as_slice()).collect();");
            em.line("let (__msgs, __trailing) = conn.call_bidi(&__method, &ctx.request_metadata().clone(), &__refs)?;");
            em.line("ctx.set_trailing(__trailing);");
            em.line("__msgs.iter().map(|m| ::grpcx_pb::ProtoCodec::decode(m).map_err(|_| ::grpcx::RpcError::Codec(\"response decode\"))).collect()");
        }
    }
    em.close_block("}");
}

fn emit_handler_sig(em: &mut Emitter, m: &crate::MethodDef, in_trait: bool) {
    let fn_name = to_snake(&m.name);
    let input = rust_type_path(&m.input);
    let output = rust_type_path(&m.output);
    let (arg, ret) = match (m.client_streaming, m.server_streaming) {
        (false, false) => (
            alloc::format!("request: {input}"),
            alloc::format!("Result<{output}, ::grpcx::Status>"),
        ),
        (false, true) => (
            alloc::format!("request: {input}"),
            alloc::format!("Result<::grpcx_pb::alloc::vec::Vec<{output}>, ::grpcx::Status>"),
        ),
        (true, false) => (
            alloc::format!("requests: ::grpcx_pb::alloc::vec::Vec<{input}>"),
            alloc::format!("Result<{output}, ::grpcx::Status>"),
        ),
        (true, true) => (
            alloc::format!("requests: ::grpcx_pb::alloc::vec::Vec<{input}>"),
            alloc::format!("Result<::grpcx_pb::alloc::vec::Vec<{output}>, ::grpcx::Status>"),
        ),
    };
    let semi = if in_trait { ";" } else { "" };
    em.line(&alloc::format!("/// `{}` rpc handler.", m.name));
    em.line(&alloc::format!(
        "fn {fn_name}(&self, {arg}, ctx: &mut ::grpcx::CallContext) -> {ret}{semi}"
    ));
}

fn emit_dispatch_bridge(em: &mut Emitter, svc: &crate::ServiceDef) {
    // `dispatch` — single-message unary entry. Bridges
    // through `dispatch_with_ctx` so peer_cred / ctx
    // semantics stay consistent across transports.
    em.open_block("fn dispatch(&self, method: &str, metadata: &::grpcx::Metadata, request: &[u8]) -> Result<(::grpcx_pb::alloc::vec::Vec<u8>, ::grpcx::Metadata), ::grpcx::RpcError> {");
    em.line("let mut __reqs = ::grpcx_pb::alloc::vec::Vec::new();");
    em.line("__reqs.push(request.to_vec());");
    em.line("let mut __ctx = ::grpcx::CallContext::new(metadata.clone());");
    em.line("let mut __resps = <Self as ::grpcx::Service>::dispatch_with_ctx(self, method, &mut __ctx, &__reqs)?;");
    em.line("Ok((__resps.pop().unwrap_or_default(), __ctx.into_trailing()))");
    em.close_block("}");
    em.blank();

    // `dispatch_streaming` — v1 transport entry
    // (h2c / h2-tls / h3 / tcp-mux v1 / ws-mux). Owns
    // its own `CallContext` (peer_cred unavailable on
    // these transports) and delegates to the shared
    // `dispatch_with_ctx` body so there is exactly one
    // copy of the method-match table.
    em.open_block("fn dispatch_streaming(&self, method: &str, metadata: &::grpcx::Metadata, requests: &[::grpcx_pb::alloc::vec::Vec<u8>]) -> Result<(::grpcx_pb::alloc::vec::Vec<::grpcx_pb::alloc::vec::Vec<u8>>, ::grpcx::Metadata), ::grpcx::RpcError> {");
    em.line("let mut __ctx = ::grpcx::CallContext::new(metadata.clone());");
    em.line("let __resps = <Self as ::grpcx::Service>::dispatch_with_ctx(self, method, &mut __ctx, requests)?;");
    em.line("Ok((__resps, __ctx.into_trailing()))");
    em.close_block("}");
    em.blank();

    // `dispatch_with_ctx` — v2 transport entry
    // (transport-uds, transport-shmem). The caller
    // owns the `CallContext` and pre-populates
    // `peer_cred`; we thread it into the handler call
    // and write trailing metadata back through `ctx`.
    em.open_block("fn dispatch_with_ctx(&self, method: &str, __ctx: &mut ::grpcx::CallContext, requests: &[::grpcx_pb::alloc::vec::Vec<u8>]) -> Result<::grpcx_pb::alloc::vec::Vec<::grpcx_pb::alloc::vec::Vec<u8>>, ::grpcx::RpcError> {");
    em.open_block("match method {");
    for m in &svc.methods {
        emit_dispatch_arm(em, m);
    }
    em.line("_ => Err(::grpcx::RpcError::Status(::grpcx::Status { code: ::grpcx::StatusCode::Unimplemented, message: ::grpcx_pb::alloc::string::String::from(\"unknown method\") })),");
    em.close_block("}");
    em.close_block("}");
}

fn emit_dispatch_arm(em: &mut Emitter, m: &crate::MethodDef) {
    let fn_name = to_snake(&m.name);
    em.open_block(&alloc::format!("\"{}\" => {{", m.name));
    // Decode request(s).
    if m.client_streaming {
        em.line("let __in: Result<::grpcx_pb::alloc::vec::Vec<_>, _> = requests.iter().map(|r| ::grpcx_pb::ProtoCodec::decode(r)).collect();");
        em.line("let __in = __in.map_err(|_| ::grpcx::RpcError::Status(::grpcx::Status { code: ::grpcx::StatusCode::InvalidArgument, message: ::grpcx_pb::alloc::string::String::from(\"request decode\") }))?;");
    } else {
        em.line("let __first: &[u8] = requests.first().map(|v| v.as_slice()).unwrap_or(&[]);");
        em.line("let __in = ::grpcx_pb::ProtoCodec::decode(__first).map_err(|_| ::grpcx::RpcError::Status(::grpcx::Status { code: ::grpcx::StatusCode::InvalidArgument, message: ::grpcx_pb::alloc::string::String::from(\"request decode\") }))?;");
    }
    // Call handler. `__ctx` is the caller-owned
    // `CallContext` carrying request metadata + peer
    // credentials in, trailing metadata out.
    em.line(&alloc::format!(
        "let __out = self.0.{fn_name}(__in, __ctx).map_err(::grpcx::RpcError::Status)?;"
    ));
    // Encode response(s).
    if m.server_streaming {
        em.line("let __resps: ::grpcx_pb::alloc::vec::Vec<::grpcx_pb::alloc::vec::Vec<u8>> = __out.iter().map(|o| { let mut b = ::grpcx_pb::alloc::vec::Vec::new(); ::grpcx_pb::ProtoCodec::encode(o, &mut b); b }).collect();");
    } else {
        em.line("let mut __b = ::grpcx_pb::alloc::vec::Vec::new();");
        em.line("::grpcx_pb::ProtoCodec::encode(&__out, &mut __b);");
        em.line("let __resps = ::grpcx_pb::alloc::vec![__b];");
    }
    em.line("Ok(__resps)");
    em.close_block("}");
}

/// `SayHello` → `say_hello` (tonic's naming habit).
fn to_snake(name: &str) -> alloc::string::String {
    let mut out = alloc::string::String::with_capacity(name.len() + 4);
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// Dotted proto type → Rust path within the generated
/// module tree: same-package types are referenced bare
/// (the stub lives in the same module as the messages);
/// dotted names map dots to `::`.
fn rust_type_path(proto_ty: &str) -> alloc::string::String {
    if proto_ty.contains('.') {
        proto_ty.replace('.', "::")
    } else {
        alloc::string::String::from(proto_ty)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn snake_case_basic() {
        assert_eq!(to_snake_case("Outer"), "outer");
        assert_eq!(to_snake_case("MyMessage"), "my_message");
        assert_eq!(to_snake_case("already_snake"), "already_snake");
        assert_eq!(to_snake_case("HTTPSConnection"), "httpsconnection");
    }

    #[test]
    fn relative_path_same_scope() {
        let cur = ["foo".to_string(), "bar".to_string()];
        let tgt = ["foo".to_string(), "bar".to_string()];
        assert_eq!(relative_path(&cur, &tgt, "Sibling"), "Sibling");
    }

    #[test]
    fn relative_path_descend() {
        let cur = ["foo".to_string(), "bar".to_string()];
        let tgt = ["foo".to_string(), "bar".to_string(), "outer".to_string()];
        assert_eq!(relative_path(&cur, &tgt, "Inner"), "outer::Inner");
    }

    #[test]
    fn relative_path_ascend() {
        let cur = ["foo".to_string(), "bar".to_string(), "outer".to_string()];
        let tgt = ["foo".to_string(), "bar".to_string()];
        assert_eq!(relative_path(&cur, &tgt, "Sibling"), "super::Sibling");
    }

    #[test]
    fn relative_path_cousin() {
        let cur = ["foo".to_string(), "bar".to_string(), "outer".to_string()];
        let tgt = ["foo".to_string(), "bar".to_string(), "another".to_string()];
        assert_eq!(relative_path(&cur, &tgt, "Type"), "super::another::Type");
    }

    #[test]
    fn escape_keyword_uses_raw_ident() {
        assert_eq!(escape_rust_ident("type"), "r#type");
        assert_eq!(escape_rust_ident("match"), "r#match");
        assert_eq!(escape_rust_ident("name"), "name");
    }

    #[test]
    fn escape_hard_keyword_uses_underscore() {
        assert_eq!(escape_rust_ident("self"), "self_");
        assert_eq!(escape_rust_ident("crate"), "crate_");
    }
}
